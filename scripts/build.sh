#!/usr/bin/env bash
# Build BeeNote: assemble every src/*.s with GNU as, link statically with ld.
# No libraries.   scripts/build.sh [release|debug]  ->  build/beenote, and
# build/beenote.exe for Windows when ld has the PE emulation (see below).
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p build/obj
MODE="${1:-release}"
VERSION="$(tr -d '[:space:]' < VERSION)"
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ ]] || { echo "bad VERSION: $VERSION" >&2; exit 1; }
printf '# generated by scripts/build.sh from VERSION\n.globl s_version\n.section .rodata\ns_version: .asciz "%s"\n.text\n' "$VERSION" > build/version.inc
ASFLAGS=(--64 -I src -I build)
[[ "$MODE" == "debug" ]] && ASFLAGS+=(-g)

# Every src/*.s is a module; main.s goes first so _start leads the text.
# plat_win.s is the Windows build's.
OBJS=()
for src in src/main.s $(LC_ALL=C ls src/*.s | grep -vE '^src/(main|plat_win)\.s$'); do
    obj="build/obj/$(basename "${src%.s}").o"
    as "${ASFLAGS[@]}" -o "$obj" "$src"
    OBJS+=("$obj")
done
if [[ "$MODE" == "debug" ]]; then
    ld -static -nostdlib -o build/beenote "${OBJS[@]}"
else
    ld -static -nostdlib -s --gc-sections --build-id=none -z noexecstack \
       -o build/beenote "${OBJS[@]}"
fi
echo "built build/beenote v$VERSION ($(stat -c %s build/beenote) bytes, mode: $MODE)"

# The Windows build: the same objects with src/plat_win.s in place of the
# Linux-only ones (main, wayland, keyboard, clipboard, plat_linux), linked
# by ld's PE emulation into build/beenote.exe (GNU ld built with the PE
# targets, as Arch's is: no mingw needed). Fixed at 0x400000 with no
# relocations: the code's 32-bit absolute addresses need an image below
# 2 GiB. (--gc-sections loses the ELF objects' symbols in a PE link.)
if ld -V 2>/dev/null | grep -qw i386pep; then
    as "${ASFLAGS[@]}" -o build/obj/plat_win.o src/plat_win.s
    WOBJS=(build/obj/plat_win.o)
    for obj in "${OBJS[@]}"; do
        [[ "$obj" =~ /(main|wayland|keyboard|clipboard|plat_linux)\.o$ ]] || WOBJS+=("$obj")
    done
    WLD=(-m i386pep -T src/plat_win.ld -e win_start --subsystem windows
         --image-base=0x400000 --disable-dynamicbase --disable-reloc-section
         --disable-high-entropy-va --nxcompat --stack 0x800000,0x800000
         --major-os-version 10 --minor-os-version 0
         --major-subsystem-version 6 --minor-subsystem-version 0)
    [[ "$MODE" == "debug" ]] || WLD+=(-s)
    ld "${WLD[@]}" -o build/beenote.exe "${WOBJS[@]}"
    echo "built build/beenote.exe v$VERSION ($(stat -c %s build/beenote.exe) bytes, mode: $MODE)"
else
    rm -f build/beenote.exe
    echo "skipped build/beenote.exe (needs ld with the i386pep emulation)"
fi
